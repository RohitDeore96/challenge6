/**
 * Strict validation of Gemini output (brief section 8.5).
 *
 * The model returns JSON; we validate with Zod plus content-level rules:
 * - unknown or duplicate action IDs are rejected;
 * - URLs, HTML/markup and fenced blocks are rejected;
 * - total length is bounded;
 * - anything that fails becomes an honest "AI explanation unavailable"
 *   state - the deterministic plan is never modified by Gemini output.
 */

import { z } from "zod";
import { resolveGeminiModel } from "./prompt";
import { AI_OUTPUT_LIMITS } from "@/lib/schemas";
import type { AiExplanation, AiUnavailable } from "@/lib/schemas";

/**
 * Validation limits come from the shared AI_OUTPUT_LIMITS contract in
 * schemas.ts - the same numbers the prompt asks the model for. Changing a
 * limit means changing it in ONE place (the contract), keeping the prompt,
 * this validator and the response schema aligned by construction.
 */
const MAX_EXPLANATION = AI_OUTPUT_LIMITS.maxExplanationChars;
const MAX_NOTE = AI_OUTPUT_LIMITS.maxNoteChars;
const MAX_NOTES = AI_OUTPUT_LIMITS.maxActionNotes;

const PROHIBITED_PATTERNS: RegExp[] = [
  /https?:\/\//i, // URLs
  /<\s*\/?\s*[a-z][^>]*>/i, // HTML tags
  /```/, // code fences
  /\*{1,2}[^*]+\*{1,2}/, // markdown bold/italic
  /^#{1,6}\s/m, // markdown headings
  /javascript\s*:/i,
];

export interface ValidationResult {
  ok: boolean;
  explanation?: AiExplanation;
  unavailable?: AiUnavailable;
}

function cleanRejection(message: string): ValidationResult {
  return {
    ok: false,
    unavailable: {
      status: "unavailable",
      reason: "invalid_response",
      message: `AI explanation rejected by validation: ${message} The deterministic plan is unaffected.`,
      model: resolveGeminiModel(),
    },
  };
}

function containsProhibited(text: string): string | null {
  for (const pattern of PROHIBITED_PATTERNS) {
    if (pattern.test(text)) {
      return pattern.source;
    }
  }
  return null;
}

const rawAiSchema = z.object({
  explanation: z.string().min(1).max(MAX_EXPLANATION),
  actionNotes: z
    .array(
      z.object({
        actionId: z.string().min(3).max(60),
        note: z.string().min(1).max(MAX_NOTE),
      })
    )
    .max(MAX_NOTES)
    .optional()
    .default([]),
});

/**
 * Validate raw model text into a trusted AiExplanation.
 * `approvedActionIds` is the deterministic allowlist from the plan.
 */
export function validateAiOutput(
  rawText: string,
  approvedActionIds: readonly string[]
): ValidationResult {
  // 1. Parse JSON (the model is asked for JSON only; fences are stripped
  //    defensively BEFORE validation is attempted, then rejected if they
  //    indicate the model ignored the format).
  let parsed: unknown;
  try {
    parsed = JSON.parse(rawText);
  } catch {
    return cleanRejection("output was not valid JSON");
  }

  const shape = rawAiSchema.safeParse(parsed);
  if (!shape.success) {
    return cleanRejection("output did not match the expected schema");
  }

  const { explanation, actionNotes } = shape.data;

  // 2. Content-level checks on all strings the UI may render.
  const texts = [explanation, ...actionNotes.map((n) => n.note)];
  for (const text of texts) {
    const bad = containsProhibited(text);
    if (bad) {
      return cleanRejection(`prohibited pattern found (${bad})`);
    }
  }

  // 3. Action IDs must exist, be unique and reference approved actions.
  const seen = new Set<string>();
  for (const note of actionNotes) {
    if (!approvedActionIds.includes(note.actionId)) {
      return cleanRejection(`unknown actionId "${note.actionId}"`);
    }
    if (seen.has(note.actionId)) {
      return cleanRejection(`duplicate actionId "${note.actionId}"`);
    }
    seen.add(note.actionId);
  }

  return {
    ok: true,
    explanation: {
      status: "ok",
      model: resolveGeminiModel(),
      explanation,
      actionNotes,
      disclaimer:
        `AI explanation generated by ${resolveGeminiModel()}. It is prose only - every number comes from live provider data or the deterministic engine, never from the AI.`,
    },
  };
}

/**
 * Safety net for prompt-injection-style questions: not a content filter,
 * just a length/shape guard applied before the question is embedded.
 */
export function sanitizeQuestion(raw: string): string | null {
  const trimmed = raw.trim().replace(/\s+/g, " ");
  if (trimmed.length === 0) return null;
  if (trimmed.length > 400) return trimmed.slice(0, 400);
  return trimmed;
}
